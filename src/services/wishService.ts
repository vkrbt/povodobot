function pickTags(ctx: WishContext): Tag[] {
  const tags: Tag[] = ['any'];

  // Погода
  const c = ctx.weatherCode;
  if (c === 0 || c === 1) tags.push('clear');
  else if (c === 2 || c === 3) tags.push('cloudy');
  else if ((c >= 51 && c <= 67) || (c >= 80 && c <= 82)) tags.push('rain');
  else if ((c >= 71 && c <= 77) || c === 85 || c === 86) tags.push('snow');
  else if (c === 45 || c === 48) tags.push('fog');
  else if (c >= 95) tags.push('thunder');

  // Температура
  const t = ctx.temp;
  if (t < 0) tags.push('cold');
  else if (t < 8) tags.push('chilly', 'cold');
  else if (t < 16) tags.push('mild');
  else if (t < 24) tags.push('warm');
  else tags.push('hot', 'warm');

  // Ветер
  if (ctx.wind >= 6) tags.push('windy');

  // Время заката
  const h = ctx.sunset.getHours();
  if (h >= 20) tags.push('late');
  if (h < 18) tags.push('early');

  return tags;
}

/** Возвращает случайное пожелание, подходящее под контекст. */
export function pickWish(ctx: WishContext): string {
  const tags = new Set(pickTags(ctx));
  const matching = WISHES.filter((w) => w.tags.some((t) => tags.has(t)));
  const pool = matching.length > 0 ? matching : WISHES;
  const i = Math.floor(Math.random() * pool.length);
  return pool[i].text;
}
